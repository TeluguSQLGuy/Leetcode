-- Solution 

WITH CTE AS (

SELECT NUM                               AS CURRENT_ROW,
       LAG(NUM, 1) OVER(ORDER BY ID ASC) AS PREVIOUS_ROW_1,
       LAG(NUM, 2) OVER(ORDER BY ID ASC) AS PREVIOUS_ROW_2
       
FROM LOGS)

SELECT DISTINCT CURRENT_ROW AS ConsecutiveNums

FROM CTE

WHERE CURRENT_ROW = PREVIOUS_ROW_1
AND   CURRENT_ROW = PREVIOUS_ROW_2;
